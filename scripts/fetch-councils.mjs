// Writes src/app/councils.js: every council area in England and Wales, with
// the council's name, website and (for districts) the county council above it.
// Sources: ONS Local Authority Districts (April 2025) and the GOV.UK local
// authority API. Run with: node scripts/fetch-councils.mjs
import { writeFileSync } from 'node:fs';

const ONS = 'https://services1.arcgis.com/ESMARspQHYMw9BZ9/arcgis/rest/services/LAD_APR_2025_UK_NC_v2/FeatureServer/0/query?where=1%3D1&outFields=LAD25CD,LAD25NM&returnGeometry=false&f=json';
const slugify = (n) => n.toLowerCase().replace(/&/g, 'and').replace(/[,.'’()]/g, '').replace(/\s+/g, '-');
// GOV.UK slugs that do not follow from the ONS name.
const SLUGS = { 'Bristol, City of': 'bristol', 'Herefordshire, County of': 'herefordshire', 'Kingston upon Hull, City of': 'kingston-upon-hull', 'Rhondda Cynon Taf': 'rhondda-cynon-taff', 'Vale of Glamorgan': 'vale-of-glamorgan', 'Folkestone and Hythe': 'folkestone-hythe', 'Bournemouth, Christchurch and Poole': 'bournemouth-christchurch-poole', 'Isle of Anglesey': 'isle-of-anglesey', 'City of London': 'city-of-london' };
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

const areas = (await (await fetch(ONS)).json()).features.map((f) => f.attributes).filter((a) => /^[EW]/.test(a.LAD25CD));
const out = {};
const missing = [];
for (const a of areas) {
  const slug = SLUGS[a.LAD25NM] || slugify(a.LAD25NM);
  const res = await fetch(`https://www.gov.uk/api/local-authority/${slug}`);
  if (!res.ok) { missing.push(`${a.LAD25NM} (${slug}): ${res.status}`); await sleep(300); continue; }
  const la = (await res.json()).local_authority;
  out[a.LAD25NM] = { slug: la.slug, name: la.name, url: la.homepage_url, tier: la.tier,
    ...(la.parent && { parent: { slug: la.parent.slug, name: la.parent.name, url: la.parent.homepage_url } }) };
  await sleep(300);
}
const sorted = Object.fromEntries(Object.entries(out).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync('src/app/councils.js', `// Council areas in England and Wales, keyed by ONS name (as returned by
// postcodes.io), with the council's GOV.UK details. Generated by
// scripts/fetch-councils.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.

export const COUNCILS = ${JSON.stringify(sorted, null, 2)};
`);
console.log(`${Object.keys(out).length} councils written`);
if (missing.length) console.log(`Missing:\n${missing.join('\n')}`);
